/** Conservative, dependency-free audit of a Markdown roundtrip from doocs/md.
 * This is NOT a full CommonMark parser and it never transfers fact verification to modified text.
 */
import {createHash} from 'node:crypto';
import {validateHandoffMarkdown} from './wechat-handoff.mjs';

const compact = value => String(value || '').replace(/\s+/gu, ' ').trim().toLocaleLowerCase();
const display = value => String(value || '').replace(/\s+/gu, ' ').trim().slice(0, 170);

function visibleText(markdown) {
  // Formatting-only edits should not, by themselves, count as changing factual wording.
  return String(markdown)
    .replace(/!\[([^\]]*)\]\([^\n)]*\)/gu, '$1')
    .replace(/\[([^\]]+)\]\([^\n)]*\)/gu, '$1')
    .replace(/<https?:\/\/[^>]+>/gu, match => match.slice(1, -1))
    .replace(/<\/?(?:b|strong|em|i|u|del|s|span|code)(?:\s[^>]*)?>/giu, '')
    .replace(/\*\*([^*\n]+)\*\*/gu, '$1')
    .replace(/(?<![\p{L}\p{N}])\*([^*\n]+)\*/gu, '$1')
    .replace(/__([^_\n]+)__/gu, '$1')
    .replace(/(?<![\p{L}\p{N}])_([^_\n]+)_/gu, '$1')
    .replace(/`([^`\n]+)`/gu, '$1')
    .replace(/~~([^~\n]+)~~/gu, '$1')
    .replace(/\\([\\`*{}\[\]()#+\-.!_>~|])/gu, '$1');
}

/** Markdown block heuristic: blank-line chunks, with fenced blocks kept intact.
 * HTML and unknown extensions remain visible as review-only content.
 */
export function scanMarkdownBlocks(markdown) {
  const lines = String(markdown).replace(/\r\n?/g, '\n').split('\n');
  const blocks = [];
  let inFence = null, buffer = [], startLine = 1;
  function flush(kind = 'text') {
    const raw = buffer.join('\n').trim();
    if (raw) {
      const cleaned = kind === 'code' ? raw.replace(/^(`{3,}|~{3,})[^\n]*\n?/u, '').replace(/\n?(`{3,}|~{3,})\s*$/u, '')
        : raw.replace(/^\s{0,3}(?:#{1,6}\s+|>\s*|[-*+]\s+|\d+[.)]\s+)/gmu, '');
      const plain = compact(visibleText(cleaned));
      if (plain) blocks.push({kind, plain, excerpt: display(cleaned), line: startLine});
    }
    buffer = [];
  }
  lines.forEach((line, idx) => {
    const marker = line.match(/^\s{0,3}(`{3,}|~{3,})/u);
    if (inFence) {
      buffer.push(line);
      if (marker && marker[1][0] === inFence[0] && marker[1].length >= inFence.length) {
        flush('code'); inFence = null;
      }
      return;
    }
    if (marker) {flush(); startLine = idx + 1; buffer = [line]; inFence = marker[1]; return;}
    if (!line.trim()) {flush(); return;}
    if (/^\s{0,3}(?:#{1,6}\s+|[-*+]\s+|\d+[.)]\s+|>\s+)/u.test(line)) {
      flush(); startLine = idx + 1; buffer = [line]; flush(); return;
    }
    if (!buffer.length) startLine = idx + 1;
    buffer.push(line);
  });
  flush(inFence ? 'unclosed_code' : 'text');
  return blocks;
}

export function analyzeMarkdownRoundtrip({title, paragraphs, claims = [], markdown, documentRevision = 0, layoutRevision = 0} = {}) {
  const value = validateHandoffMarkdown(markdown);
  const blocks = scanMarkdownBlocks(value);
  // Ignore only the title heading that was generated by our own source handoff.
  const titleNorm = compact(title);
  if (blocks[0]?.plain === titleNorm && /^\s*#\s+/u.test(value)) blocks.shift();
  const used = new Set(), matchedIndices = [];
  const sourceBlocks = (paragraphs || []).map(p => {
    const normalized = compact(p.text);
    const i = blocks.findIndex((b, j) => !used.has(j) && b.plain === normalized);
    if (i !== -1) {used.add(i); matchedIndices.push(i);}
    const attached = claims.filter(c => c.paragraphId === p.id);
    return {
      paragraphId: p.id,
      excerpt: display(p.text),
      status: i >= 0 ? 'exact_text' : 'requires_review',
      matchLine: i >= 0 ? blocks[i].line : null,
      linkedClaims: attached.length,
      evidenceReview: attached.some(c => c.anchorStatus !== 'matched' || c.needsResearchReview) || (i < 0 && attached.length > 0),
    };
  });
  const addedBlocks = blocks.filter((_, index) => !used.has(index)).map(({kind,excerpt,line}) => ({kind,excerpt,line}));
  const unmatchedSource = sourceBlocks.filter(b => b.status !== 'exact_text');
  const reorderedBlocks = matchedIndices.some((i,j) => j>0 && i < matchedIndices[j-1]);
  // URLs and images are content too: a change of link target must not pass as formatting-only.
  const linkTargets = [...value.matchAll(/!?\[[^\]\n]*\]\((https?:\/\/[^)\s]+)(?:\s+[^)]*)?\)|<img\s+[^>]*src=["'](https?:\/\/[^"']+)["']/giu)]
    .map(m => m[1] || m[2]);
  const originalText = (paragraphs || []).map(p => p.text).join('\n');
  const newLinks = [...new Set(linkTargets.filter(url => !originalText.includes(url)))].slice(0,40);

  const affectedEvidence = sourceBlocks.filter(b => b.evidenceReview);
  const summary = {
    sourceBlocks: sourceBlocks.length,
    exactText: sourceBlocks.length - unmatchedSource.length,
    sourceNeedsReview: unmatchedSource.length,
    newOrChangedBlocks: addedBlocks.length,
    affectedEvidence: affectedEvidence.length,
    reorderedBlocks: reorderedBlocks ? 1 : 0,
    newLinkTargets: newLinks.length,
  };
  const hasMaterialDrift = unmatchedSource.length > 0 || addedBlocks.length > 0 || reorderedBlocks || newLinks.length > 0;
  const requiresHumanReview = hasMaterialDrift || affectedEvidence.length > 0;
  const reviewToken = createHash('sha256').update(JSON.stringify([documentRevision,layoutRevision,value])).digest('hex');
  return {
    summary, sourceBlocks, newLinks, reorderedBlocks, requiresHumanReview, addedBlocks:addedBlocks.slice(0,80),
    truncatedAddedBlocks:Math.max(0,addedBlocks.length - 80),hasMaterialDrift,
    reviewToken,documentRevision,layoutRevision,
    limitations: 'Conservative text-level comparison; matching a sentence does not verify it, and formatting/complex Markdown can cause false alarms. Imported Markdown does not inherit paragraph evidence automatically.',
  };
}
