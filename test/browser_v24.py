def check(name,condition):
    passed=bool(condition);results.append({'name':name,'passed':passed}); print(('PASS' if passed else 'FAIL'),name,flush=True)
    if not passed: raise AssertionError(name)
def respond(route):
    req=route.request
    try:
        payload=req.post_data.encode() if req.post_data is not None else None
        with urlopen(Request(req.url,method=req.method,data=payload,headers={'Content-Type':'application/json'}),timeout=9) as r:
            return route.fulfill(status=r.status,content_type='application/json',body=r.read(),headers={'Access-Control-Allow-Origin':'*'})
    except HTTPError as e: return route.fulfill(status=e.code,content_type='application/json',body=e.read(),headers={'Access-Control-Allow-Origin':'*'})
    except Exception as e: return route.fulfill(status=502,content_type='application/json',body=json.dumps({'error':str(e)}),headers={'Access-Control-Allow-Origin':'*'})
