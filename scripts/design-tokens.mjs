import { readFile, writeFile } from 'node:fs/promises'

const tokens = JSON.parse(await readFile('docs/ux/design-tokens.json', 'utf8'))
// 语义选中态 token（DESIGN-SYSTEM.md v2.3「选中态规范」，UX 修复方案 N3）：
// 视图切换类平台/tab 选中 = 浅陶土；勾选/多选行选中 = 浅绿底。取值不在 design-tokens.json，见生成器本节。
const semanticColors = {
  'selected-platform': '#f3e4d7',
  'selected-row': '#eaf1e2',
}
const lines = [':root {', '  color-scheme: light;']
for (const [name, value] of Object.entries(tokens.color)) lines.push(`  --${name}: ${value};`)
for (const [name, value] of Object.entries(semanticColors)) lines.push(`  --${name}: ${value};`)
for (const [name, value] of Object.entries(tokens.layout)) lines.push(`  --size-${name}: ${value};`)
lines.push(
  `  --radius: ${tokens.radius.base};`,
  '}',
  '',
)
const source =
  '/* Generated by scripts/design-tokens.mjs from docs/ux/design-tokens.json plus generator-defined semantic tokens. */\n' +
  lines.join('\n')
if (process.argv.includes('--check')) {
  if ((await readFile('packages/ui/src/tokens.css', 'utf8')) !== source)
    throw new Error('Design tokens are out of sync; run pnpm tokens:generate')
  console.log('Theme matches the confirmed design palette; type and spacing use Tailwind defaults.')
} else await writeFile('packages/ui/src/tokens.css', source)
